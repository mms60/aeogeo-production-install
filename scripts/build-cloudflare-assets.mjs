import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const source = "site";
const output = ".cloudflare/site";

rmSync(".cloudflare", { recursive: true, force: true });
mkdirSync(dirname(output), { recursive: true });
cpSync(source, output, { recursive: true });

const sourceRedirects = readFileSync(join(source, "_redirects"), "utf8");
const redirects = [];
let skipped = 0;

for (const rawLine of sourceRedirects.split(/\r?\n/)) {
  const line = rawLine.trim();
  if (!line || line.startsWith("#")) continue;

  const parts = line.split(/\s+/);
  if (parts.length < 3) {
    skipped += 1;
    continue;
  }

  const [from, to] = parts;
  const status = parts[parts.length - 1].replace(/!$/, "");

  // Cloudflare's static-asset HTML handling already serves /page from
  // /page.html and /folder/ from /folder/index.html. A 200 rewrite to those
  // files makes Cloudflare redirect back to the extensionless URL and can loop.
  // Netlify keeps using the source _redirects unchanged.
  if (status === "200" || status === "404") {
    skipped += 1;
    continue;
  }

  if (!["301", "302", "303", "307", "308"].includes(status)) {
    skipped += 1;
    continue;
  }

  redirects.push(`${from} ${to} ${status}`);
}

writeFileSync(
  join(output, "_redirects"),
  [
    "# Generated by scripts/build-cloudflare-assets.mjs.",
    "# Source: site/_redirects. Do not edit the generated copy by hand.",
    ...redirects,
    "",
  ].join("\n"),
);

const headers = `# Generated by scripts/build-cloudflare-assets.mjs.
# Mirrors the headers in netlify.toml for the Cloudflare static preview.

/account/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer

/auth/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer

/geo-audit/run/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer

/service-checkout/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer

/content-order/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer
  X-Robots-Tag: noindex, nofollow, noarchive

/content-review/*
  Cache-Control: no-store
  Referrer-Policy: no-referrer
  X-Robots-Tag: noindex, nofollow, noarchive

/owner-billing-check/*
  X-Robots-Tag: noindex, nofollow, noarchive

/owner-monthly-test/*
  X-Robots-Tag: noindex, nofollow, noarchive

/competitor-intelligence/sample-preview*
  X-Robots-Tag: noindex, nofollow, noarchive

/directory-listing-kit/thanks/*
  X-Robots-Tag: noindex, nofollow, noarchive
`;

writeFileSync(join(output, "_headers"), headers);

console.log(
  `Cloudflare assets ready in ${output}: ${redirects.length} redirects, ${skipped} Netlify-only rules skipped.`,
);
