-- ---------------------------------------------------------------------------
-- 11. Atomic operations
-- ---------------------------------------------------------------------------
-- These exist at the database layer because the guarantees they provide
-- (single-winner webhook processing, one entitlement per purchase, complete
-- test cleanup) cannot be made reliable from concurrent Netlify instances.

-- Claims a Stripe event exactly once. Returns true only for the first caller.
create or replace function public.content_decay_claim_webhook(
  p_event_id text,
  p_type text,
  p_livemode boolean,
  p_test_run uuid default null
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_event_id is null or p_event_id !~ '^evt_[A-Za-z0-9_]{8,}$'
     or p_type is null or p_livemode is null then
    return false;
  end if;
  -- A live event can never be recorded as part of a test run, or the reverse.
  if p_livemode and p_test_run is not null then
    return false;
  end if;

  insert into public.content_decay_webhook_events
    (id, event_type, livemode, environment, test_run_id)
  values (
    p_event_id,
    p_type,
    p_livemode,
    case when p_livemode then 'live' else 'test' end,
    case when p_livemode then null else p_test_run end
  )
  on conflict (id) do nothing;

  -- FOUND is false when the conflict clause suppressed the insert, which means
  -- another instance already claimed this event.
  return found;
end;
$$;

-- Grants the entitlement for a paid purchase. Idempotent: repeat calls return
-- the same entitlement id. Returns null when the purchase is not payable.
create or replace function public.content_decay_grant_entitlement(p_purchase uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  p public.content_decay_purchases%rowtype;
  grant_id uuid;
begin
  select * into p from public.content_decay_purchases where id = p_purchase;
  if not found or p.status <> 'paid' or p.user_id is null then
    return null;
  end if;

  insert into public.content_decay_entitlements
    (user_id, scan_id, purchase_id, status, environment, test_run_id)
  values
    (p.user_id, p.scan_id, p.id, 'active', p.environment, p.test_run_id)
  on conflict (purchase_id) do update
    set status = 'active',
        updated_at = now()
    where public.content_decay_entitlements.status <> 'active'
  returning id into grant_id;

  if grant_id is null then
    select id into grant_id
      from public.content_decay_entitlements
     where purchase_id = p.id;
  end if;

  return grant_id;
end;
$$;

-- Marks the purchase behind a Stripe refund as refunded and revokes its
-- entitlement in one call, so a refund cannot leave an active entitlement
-- behind. Idempotent: repeated refund events return the same purchase id, and
-- the mode filter prevents a live refund from touching a test purchase.
create or replace function public.content_decay_refund_purchase(
  p_payment_intent text,
  p_livemode boolean
) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  p public.content_decay_purchases%rowtype;
begin
  if p_payment_intent is null or p_payment_intent !~ '^pi_[A-Za-z0-9_]+$'
     or p_livemode is null then
    return null;
  end if;

  select * into p
    from public.content_decay_purchases
   where stripe_payment_intent = p_payment_intent
     and livemode = p_livemode
   for update;
  if not found then
    return null;
  end if;

  update public.content_decay_purchases
     set status = 'refunded',
         updated_at = now()
   where id = p.id
     and status <> 'refunded';

  update public.content_decay_entitlements
     set status = 'revoked',
         updated_at = now()
   where purchase_id = p.id
     and status = 'active';

  return p.id;
end;
$$;

-- Marks the purchase behind a Stripe dispute as revoked and revokes its
-- entitlement in one call, so a disputed payment cannot keep the paid report
-- open. A dispute is not a refund, so a purchase that was already refunded keeps
-- that status while its entitlement is still revoked. Idempotent: repeated
-- dispute events return the same purchase id, and the mode filter prevents a
-- live dispute from touching a test purchase.
create or replace function public.content_decay_dispute_purchase(
  p_payment_intent text,
  p_livemode boolean
) returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  p public.content_decay_purchases%rowtype;
begin
  if p_payment_intent is null or p_payment_intent !~ '^pi_[A-Za-z0-9_]+$'
     or p_livemode is null then
    return null;
  end if;

  select * into p
    from public.content_decay_purchases
   where stripe_payment_intent = p_payment_intent
     and livemode = p_livemode
   for update;
  if not found then
    return null;
  end if;

  update public.content_decay_purchases
     set status = 'revoked',
         updated_at = now()
   where id = p.id
     and status = 'paid';

  update public.content_decay_entitlements
     set status = 'revoked',
         updated_at = now()
   where purchase_id = p.id
     and status = 'active';

  return p.id;
end;
$$;

-- The single server-side access check for paid report content. Requires an
-- active entitlement AND a paid purchase AND matching environments.
create or replace function public.content_decay_access(
  p_user uuid,
  p_scan uuid,
  p_environment text
) returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
      from public.content_decay_entitlements e
      join public.content_decay_purchases p on p.id = e.purchase_id
     where e.user_id = p_user
       and e.scan_id = p_scan
       and e.status = 'active'
       and p.status = 'paid'
       and e.environment = p_environment
       and p.environment = p_environment
       and (e.expires_at is null or e.expires_at > now())
  );
$$;

-- Removes every row belonging to one test run. Webhook ledger rows are kept.
create or replace function public.content_decay_test_cleanup(p_run uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  n_findings integer;
  n_pages integer;
  n_reports integer;
  n_entitlements integer;
  n_purchases integer;
  n_scans integer;
begin
  if p_run is null then
    return jsonb_build_object('cleaned', false, 'reason', 'missing_run');
  end if;
  if not exists (select 1 from public.content_decay_test_runs where id = p_run) then
    return jsonb_build_object('cleaned', false, 'reason', 'unknown_run');
  end if;

  delete from public.content_decay_findings f
   using public.content_decay_scans s
   where f.scan_id = s.id and s.test_run_id = p_run;
  get diagnostics n_findings = row_count;

  delete from public.content_decay_scan_pages pg
   using public.content_decay_scans s
   where pg.scan_id = s.id and s.test_run_id = p_run;
  get diagnostics n_pages = row_count;

  delete from public.content_decay_reports r
   using public.content_decay_scans s
   where r.scan_id = s.id and s.test_run_id = p_run;
  get diagnostics n_reports = row_count;

  delete from public.content_decay_entitlements e
   using public.content_decay_scans s
   where e.scan_id = s.id and s.test_run_id = p_run;
  get diagnostics n_entitlements = row_count;

  delete from public.content_decay_purchases pu
   using public.content_decay_scans s
   where pu.scan_id = s.id and s.test_run_id = p_run;
  get diagnostics n_purchases = row_count;

  delete from public.content_decay_scans s where s.test_run_id = p_run;
  get diagnostics n_scans = row_count;

  update public.content_decay_test_runs
     set cleaned_at = coalesce(cleaned_at, now())
   where id = p_run;

  return jsonb_build_object(
    'cleaned', true,
    'findings', n_findings,
    'pages', n_pages,
    'reports', n_reports,
    'entitlements', n_entitlements,
    'purchases', n_purchases,
    'scans', n_scans
  );
end;
$$;

-- Scoped rate limiting. Reuses the shared durable counter from
-- 11-audit-rate-limits.sql instead of adding a second near-identical table.
create or replace function public.consume_content_decay_rate_limit(
  p_key text,
  p_limit integer,
  p_window_seconds integer
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_key is null or length(p_key) < 8 then
    return false;
  end if;
  return public.consume_audit_rate_limit('content-decay:' || p_key, p_limit, p_window_seconds);
end;
$$;

