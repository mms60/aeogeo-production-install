-- ---------------------------------------------------------------------------
-- SECURITY MODEL
-- ---------------------------------------------------------------------------
-- Every table below is deny-all for the browser roles (anon, authenticated).
-- RLS is enabled and deliberately NO select/insert/update/delete policies are
-- created. All access goes through the Netlify functions using the service role.
--
-- Why no "read your own scan" policy: the findings, recommendations and
-- suggested replacement paragraphs ARE the paid product. A select-own policy
-- would let any signed-in visitor read those rows straight from the public REST
-- API after a free scan, without paying. Ownership is therefore checked in the
-- function layer together with an active entitlement.
--
-- ---------------------------------------------------------------------------
-- TEST ISOLATION
-- ---------------------------------------------------------------------------
-- Rows created in Stripe test mode carry environment = 'test' AND a test_run_id.
-- Live rows carry environment = 'live' and no test_run_id. Check constraints
-- enforce that pairing, so a test row can never be mistaken for a live one.
-- Child rows (pages, findings) have no environment column: they inherit it from
-- their scan, which removes any chance of a page disagreeing with its scan.
--
-- content_decay_test_cleanup(run_id) removes every row belonging to one test
-- run. Webhook ledger rows are intentionally retained: they are the replay and
-- idempotency record, and deleting them would allow a replayed event to be
-- processed a second time.

