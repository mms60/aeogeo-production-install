-- ---------------------------------------------------------------------------
-- 2. Scans
-- ---------------------------------------------------------------------------
-- public_token is generated by the database so the anonymous free scan always
-- has an unguessable handle without the function having to remember to set one.
create table if not exists public.content_decay_scans (
  id uuid primary key default gen_random_uuid(),
  public_token text not null unique
    default encode(gen_random_bytes(24), 'hex'),
  user_id uuid references auth.users(id) on delete set null,
  environment text not null default 'live'
    check (environment in ('live', 'test')),
  test_run_id uuid references public.content_decay_test_runs(id) on delete cascade,
  target_url text not null,
  hostname text not null,
  page_limit integer not null default 10 check (page_limit between 1 and 10),
  pages_scanned integer not null default 0 check (pages_scanned >= 0),
  status text not null default 'queued'
    check (status in ('queued', 'running', 'completed', 'failed')),
  overall_score integer check (overall_score between 0 and 100),
  summary jsonb,
  error_code text,
  -- Hashed client identifier only; never a raw IP address.
  client_key text check (client_key is null or client_key ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  completed_at timestamptz,
  constraint content_decay_scans_id_owner unique (id, user_id),
  constraint content_decay_scans_environment_run check (
    (environment = 'live' and test_run_id is null) or
    (environment = 'test' and test_run_id is not null)
  )
);

-- ---------------------------------------------------------------------------
-- 3. Scanned pages
-- ---------------------------------------------------------------------------
create table if not exists public.content_decay_scan_pages (
  id uuid primary key default gen_random_uuid(),
  scan_id uuid not null references public.content_decay_scans(id) on delete cascade,
  url text not null,
  http_status integer,
  title text,
  word_count integer check (word_count >= 0),
  content_hash text,
  last_modified_header timestamptz,
  declared_modified_at timestamptz,
  page_score integer check (page_score between 0 and 100),
  severity text check (severity in ('critical', 'high', 'medium', 'low')),
  signals jsonb not null default '{}'::jsonb,
  fetched_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 4. Findings (paid content)
-- ---------------------------------------------------------------------------
create table if not exists public.content_decay_findings (
  id uuid primary key default gen_random_uuid(),
  scan_id uuid not null references public.content_decay_scans(id) on delete cascade,
  page_id uuid references public.content_decay_scan_pages(id) on delete cascade,
  category text not null check (category in (
    'outdated_data', 'missing_information', 'structure',
    'ai_readiness', 'freshness', 'factual_support'
  )),
  code text not null,
  severity text not null check (severity in ('critical', 'high', 'medium', 'low')),
  priority integer not null default 0,
  title text not null,
  detail text,
  evidence text,
  recommendation text,
  suggested_replacement text,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 5. Paid reports
-- ---------------------------------------------------------------------------
-- The composite foreign key guarantees a report can only ever be attached to a
-- scan owned by the same user. A cross-account report is impossible at the
-- storage layer, not just in application code.
create table if not exists public.content_decay_reports (
  id uuid primary key default gen_random_uuid(),
  scan_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'queued'
    check (status in ('queued', 'generating', 'ready', 'failed')),
  format_version integer not null default 1,
  page_count integer not null default 0 check (page_count >= 0),
  pdf_bytes integer check (pdf_bytes >= 0),
  pdf_sha256 text check (pdf_sha256 is null or pdf_sha256 ~ '^[0-9a-f]{64}$'),
  error_code text,
  generated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_decay_reports_scan_owner
    foreign key (scan_id, user_id)
    references public.content_decay_scans(id, user_id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- 6. Purchases (one-time $19.99)
-- ---------------------------------------------------------------------------
create table if not exists public.content_decay_purchases (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  scan_id uuid not null,
  email text,
  status text not null default 'paid'
    check (status in ('paid', 'refunded', 'revoked')),
  stripe_session_id text not null unique,
  stripe_payment_intent text,
  stripe_price_id text,
  amount_total integer check (amount_total >= 0),
  currency text not null default 'usd',
  livemode boolean not null default false,
  environment text not null default 'live'
    check (environment in ('live', 'test')),
  test_run_id uuid references public.content_decay_test_runs(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_decay_purchases_scan_owner
